constexpr double pi = 3.14159265358979323846;

std::int32_t clampToInt32(std::int64_t value) noexcept {
    const auto minimum = static_cast<std::int64_t>(
        std::numeric_limits<std::int32_t>::min()
    );
    const auto maximum = static_cast<std::int64_t>(
        std::numeric_limits<std::int32_t>::max()
    );
    return static_cast<std::int32_t>(std::clamp(value, minimum, maximum));
}

std::uint32_t checkedDimension(std::int64_t value) {
    if (value <= 0) {
        return 1;
    }
    if (value > static_cast<std::int64_t>(
                    std::numeric_limits<std::uint32_t>::max())) {
        throw std::invalid_argument("Transformed image dimensions are too large.");
    }
    return static_cast<std::uint32_t>(value);
}

[[nodiscard]] std::vector<LayerId> layerIds(const Document& document) {
    std::vector<LayerId> ids;
    ids.reserve(document.layerCount());
    for (const Layer& layer : document.layerStack().layers()) {
        ids.push_back(layer.id());
    }
    return ids;
}

struct BilinearSample {
    float r{0.0F};
    float g{0.0F};
    float b{0.0F};
    float a{0.0F};
    float weight{0.0F};
};

// Sample using premultiplied alpha so transparent pixels do not bleed colour
// into opaque neighbours. (x, y) is in source pixel coordinates; samples
// outside the image contribute nothing.
BilinearSample samplePremultiplied(
    const ImageBuffer& source,
    double x,
    double y
) {
    BilinearSample result;
    if (!std::isfinite(x) || !std::isfinite(y)) {
        return result;
    }

    const auto x0 = static_cast<std::int64_t>(std::floor(x));
    const auto y0 = static_cast<std::int64_t>(std::floor(y));
    const double fx = x - static_cast<double>(x0);
    const double fy = y - static_cast<double>(y0);

    for (int dy = 0; dy <= 1; ++dy) {
        for (int dx = 0; dx <= 1; ++dx) {
            const std::int64_t sx = x0 + dx;
            const std::int64_t sy = y0 + dy;
            if (sx < 0 || sy < 0 ||
                sx >= static_cast<std::int64_t>(source.width()) ||
                sy >= static_cast<std::int64_t>(source.height())) {
                continue;
            }

            const double wx = dx == 0 ? 1.0 - fx : fx;
            const double wy = dy == 0 ? 1.0 - fy : fy;
            const double weight = wx * wy;
            if (weight <= 0.0) {
                continue;
            }

            const Pixel pixel = source.getPixel(
                static_cast<std::uint32_t>(sx),
                static_cast<std::uint32_t>(sy)
            );
            const float alpha = static_cast<float>(pixel.a) / 255.0F;
            result.r += static_cast<float>(pixel.r) * alpha *
                        static_cast<float>(weight);
            result.g += static_cast<float>(pixel.g) * alpha *
                        static_cast<float>(weight);
            result.b += static_cast<float>(pixel.b) * alpha *
                        static_cast<float>(weight);
            result.a += alpha * static_cast<float>(weight);
            result.weight += static_cast<float>(weight);
        }
    }
    return result;
}

Pixel unpremultiply(const BilinearSample& sample) {
    if (sample.a <= 1.0e-6F) {
        return Pixel{0, 0, 0, 0};
    }
    const auto toByte = [](float value) {
        return static_cast<std::uint8_t>(
            std::clamp(std::lround(value), 0L, 255L)
        );
    };
    return Pixel{
        toByte(sample.r / sample.a),
        toByte(sample.g / sample.a),
        toByte(sample.b / sample.a),
        toByte(sample.a * 255.0F)
    };
}

bool nearlyQuarterTurn(double degrees, int& quarterTurns) noexcept {
    if (!std::isfinite(degrees)) {
        return false;
    }
    const double turns = degrees / 90.0;
    const double rounded = std::round(turns);
    if (std::abs(turns - rounded) > 1.0e-9) {
        return false;
    }
    quarterTurns = static_cast<int>(rounded) % 4;
    if (quarterTurns < 0) {
        quarterTurns += 4;
    }
    return true;
}

std::uint32_t scaleTextDimension(std::uint32_t value, double factor) noexcept {
    if (value == 0) {
        return 0;
    }
    const double scaled = std::round(static_cast<double>(value) * factor);
    const double clamped = std::clamp(
        scaled,
        1.0,
        static_cast<double>(TextLayerData::maxBoxDimension)
    );
    return static_cast<std::uint32_t>(clamped);
}

// Scale a text payload when the whole document (or a single text layer) is
// resampled. Text stays editable: the font size and box follow the scale
// factors and the rendered cache is regenerated by the application renderer.
void scaleTextPayload(TextLayerData& data, double scaleX, double scaleY) noexcept {
    const double average = (scaleX + scaleY) * 0.5;
    const auto scaledFont = static_cast<double>(data.style.fontSize) * average;
    data.style.fontSize = static_cast<float>(
        std::clamp(scaledFont, 1.0, 100000.0)
    );
    const auto scaledSpacing =
        static_cast<double>(data.style.letterSpacing) * average;
    data.style.letterSpacing = static_cast<float>(
        std::clamp(scaledSpacing, -10000.0, 10000.0)
    );
    data.boxWidth = scaleTextDimension(data.boxWidth, scaleX);
    data.boxHeight = scaleTextDimension(data.boxHeight, scaleY);
}

// Vector layers keep their geometry in document coordinates and use the layer
// ImageBuffer purely as a regenerable cache. Document transforms therefore
// rewrite the geometry and leave the cache for the application renderer to
// refresh (see ShapeRenderer::refreshDocument).
void scaleShapePayload(
    ShapeLayerData& shape,
    double originX,
    double originY,
    double scaleX,
    double scaleY
) noexcept {
    scaleShape(shape, originX, originY, scaleX, scaleY);
    sanitizeShape(shape);
}

void rotateShapePayload(
    ShapeLayerData& shape,
    double pivotX,
    double pivotY,
    double degrees
) noexcept {
    rotateShape(shape, pivotX, pivotY, degrees);
    sanitizeShape(shape);
}

bool applyDocumentOperation(
    Document& document,
    DocumentSnapshot& before,
    bool& captured,
    const std::function<void(Document&)>& operation
) {
    if (!captured) {
        before = captureDocumentSnapshot(document);
        captured = true;
    }

    try {
        operation(document);
        return true;
    } catch (...) {
        restoreDocumentSnapshot(document, before);
        return false;
    }
}


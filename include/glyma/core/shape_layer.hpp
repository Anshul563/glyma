#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

#include "glyma/core/pixel.hpp"

namespace glyma::core {

// The geometric primitive a vector layer draws. Rectangular shapes are defined
// by an axis-aligned bounding box; line-based shapes by two endpoints; polygons
// by an explicit vertex list.
enum class ShapeType : std::uint8_t {
    Rectangle,
    Ellipse,
    Line,
    Arrow,
    RoundedRectangle,
    Polygon,
};

// Stroke dash pattern.
enum class StrokeStyle : std::uint8_t {
    Solid,
    Dashed,
    Dotted,
};

// A vertex in document coordinates.
struct ShapePoint {
    double x{0.0};
    double y{0.0};
};

// Fill paint for closed shapes.
struct ShapeFill {
    bool enabled{true};
    Pixel color{210, 210, 214, 255};
};

// Stroke paint shared by every shape type.
struct ShapeStroke {
    bool enabled{true};
    Pixel color{24, 24, 28, 255};
    // Stroke width in document pixels. Zero disables the stroke.
    float width{2.0F};
    StrokeStyle style{StrokeStyle::Solid};
};

// Arrowhead decoration for Arrow shapes.
struct ArrowHead {
    bool start{false};
    bool end{true};
    // Head size in document pixels.
    float length{14.0F};
    float width{10.0F};
};

// An axis-aligned bounding box in document coordinates.
struct ShapeBounds {
    double x{0.0};
    double y{0.0};
    double width{0.0};
    double height{0.0};

    [[nodiscard]] double right() const noexcept { return x + width; }
    [[nodiscard]] double bottom() const noexcept { return y + height; }
    [[nodiscard]] double centreX() const noexcept { return x + width * 0.5; }
    [[nodiscard]] double centreY() const noexcept { return y + height * 0.5; }
    [[nodiscard]] bool isEmpty() const noexcept {
        return width <= 0.0 || height <= 0.0;
    }
};

// The editable payload of a vector layer. All geometry is stored in document
// coordinates so shapes survive canvas transforms without rasterization. The
// layer's ImageBuffer is a rendered cache regenerated by the application
// renderer and is never the authoritative representation.
//
// Rotation is clockwise in screen space (y grows downward) about the geometry
// bounds centre (see shapeCentre()). Rectangular shapes keep an unrotated
// bounding box plus this rotation angle; the geometry itself is never baked.
struct ShapeLayerData {
    // Conservative limits shared with the renderer and the file format.
    static constexpr double maxCoordinate = 1.0e7;
    static constexpr double maxDimension = 65535.0;
    static constexpr float maxStrokeWidth = 4096.0F;
    static constexpr std::size_t maxPoints = 4096;

    ShapeType type{ShapeType::Rectangle};

    // Axis-aligned geometry bounds (document coordinates). Always normalized so
    // width and height are non-negative. Kept in sync with the primary
    // geometry (endpoints for lines, vertices for polygons).
    double x{0.0};
    double y{0.0};
    double width{0.0};
    double height{0.0};

    // Line and arrow endpoints (document coordinates).
    double startX{0.0};
    double startY{0.0};
    double endX{0.0};
    double endY{0.0};

    // Polygon vertices (document coordinates).
    std::vector<ShapePoint> points;

    // Extra rotation in degrees, clockwise, about the geometry bounds centre.
    double rotation{0.0};

    // Corner radius for RoundedRectangle, in document pixels.
    float cornerRadius{0.0F};

    ShapeFill fill;
    ShapeStroke stroke;
    ArrowHead arrow;

    // Throws std::invalid_argument when the payload cannot be rendered or
    // stored (non-finite numbers, out-of-range sizes, too many vertices).
    void validate() const;
    [[nodiscard]] bool isValid() const noexcept;
};

// String conversions kept Qt-free so the engine and file format can round-trip.
[[nodiscard]] const char* shapeTypeName(ShapeType type) noexcept;
[[nodiscard]] bool parseShapeType(const std::string& value, ShapeType& out) noexcept;
[[nodiscard]] const char* strokeStyleName(StrokeStyle style) noexcept;
[[nodiscard]] bool parseStrokeStyle(
    const std::string& value,
    StrokeStyle& out
) noexcept;

// True for shapes defined by a bounding box (Rectangle/Ellipse/RoundedRectangle).
[[nodiscard]] bool isBoxShape(ShapeType type) noexcept;
// True for shapes defined by two endpoints (Line/Arrow).
[[nodiscard]] bool isLineShape(ShapeType type) noexcept;

// Normalize an unordered drag rectangle into a non-negative box.
[[nodiscard]] ShapeBounds normalizeRect(
    double x0,
    double y0,
    double x1,
    double y1
) noexcept;

// Rotate a box's four corners about (pivotX, pivotY) and return the enclosing
// axis-aligned box.
[[nodiscard]] ShapeBounds rotateBounds(
    const ShapeBounds& bounds,
    double pivotX,
    double pivotY,
    double degrees
) noexcept;

// The unrotated geometry bounds (document coordinates).
[[nodiscard]] ShapeBounds shapeGeometryBounds(const ShapeLayerData& shape) noexcept;
// Rotation anchor: the centre of the unrotated geometry bounds.
[[nodiscard]] ShapePoint shapeCentre(const ShapeLayerData& shape) noexcept;
// The axis-aligned bounds of the rotated shape, including stroke width and
// arrowheads. Used for cache sizing and selection overlays.
[[nodiscard]] ShapeBounds shapeVisualBounds(const ShapeLayerData& shape) noexcept;

// Primary-geometry mutators. All keep the bounds fields consistent.
void setRectGeometry(
    ShapeLayerData& shape,
    double x,
    double y,
    double width,
    double height
) noexcept;
void setLineGeometry(
    ShapeLayerData& shape,
    double startX,
    double startY,
    double endX,
    double endY
) noexcept;
void setPolygonGeometry(ShapeLayerData& shape, std::vector<ShapePoint> points) noexcept;
// Recompute the bounds fields from the primary geometry (line/polygon).
void syncShapeBounds(ShapeLayerData& shape) noexcept;

// Translate every defining coordinate.
void translateShape(ShapeLayerData& shape, double dx, double dy) noexcept;
// Scale every defining coordinate about a document-space origin.
void scaleShape(
    ShapeLayerData& shape,
    double originX,
    double originY,
    double scaleX,
    double scaleY
) noexcept;
// Rotate the shape about a document-space pivot: the centre moves and the
// rotation angle accumulates. The stored geometry stays unrotated.
void rotateShape(
    ShapeLayerData& shape,
    double pivotX,
    double pivotY,
    double degrees
) noexcept;
// Mirror the shape across a canvas edge and adjust its rotation.
void flipShape(
    ShapeLayerData& shape,
    bool horizontal,
    double canvasWidth,
    double canvasHeight
) noexcept;

// Hit test a document-space point against the shape. `tolerance` is an extra
// document-space slack (typically a few screen pixels converted to document
// units). Accounts for rotation and stroke width.
[[nodiscard]] bool shapeHitTest(
    const ShapeLayerData& shape,
    double documentX,
    double documentY,
    double tolerance
) noexcept;

// Clamp all numeric fields into valid ranges (used defensively before render).
void sanitizeShape(ShapeLayerData& shape) noexcept;

} // namespace glyma::core

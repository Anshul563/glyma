#pragma once

#include <cstdint>
#include <string>

#include "glyma/core/pixel.hpp"

namespace glyma::core {

// Horizontal alignment of text inside its box.
enum class TextHorizontalAlign : std::uint8_t {
    Left,
    Center,
    Right,
};

// Vertical alignment of the text block inside its box.
enum class TextVerticalAlign : std::uint8_t {
    Top,
    Middle,
    Bottom,
};

// Typography attributes for a text layer. All values are stored in document
// pixel units so the model stays resolution-independent from any renderer.
struct TextStyle {
    std::string fontFamily{"Sans Serif"};
    // Font size in pixels (not points), so layout matches document pixels.
    float fontSize{32.0F};
    // CSS-style weight in the range 1..1000 (400 = regular, 700 = bold).
    int fontWeight{400};
    bool italic{false};
    Pixel color{0, 0, 0, 255};
    // Line height as a multiple of the font's natural line height.
    float lineSpacing{1.0F};
    // Extra spacing between glyphs in pixels; may be negative.
    float letterSpacing{0.0F};
    TextHorizontalAlign horizontalAlign{TextHorizontalAlign::Left};
    TextVerticalAlign verticalAlign{TextVerticalAlign::Top};
    // When true, the text wraps to the box width at word boundaries.
    bool wordWrap{false};

    [[nodiscard]] bool operator==(const TextStyle&) const = default;
};

// The editable payload of a text layer. The layer's X/Y offset positions the
// box relative to the canvas; the layer's ImageBuffer holds a rendered cache
// that is regenerated by the application renderer.
//
// When `autoSize` is true the box grows to fit the text and `boxWidth` /
// `boxHeight` are refreshed by the renderer to record the measured bounds.
// When `autoSize` is false the text is laid out inside `boxWidth` x
// `boxHeight` and aligned according to the style.
struct TextLayerData {
    // Conservative per-dimension and total limits shared with the renderer.
    static constexpr std::uint32_t maxBoxDimension = 65535;
    static constexpr std::uint64_t maxPixelCount = 64ULL * 1024ULL * 1024ULL;

    std::string text;
    TextStyle style;
    bool autoSize{true};
    std::uint32_t boxWidth{0};
    std::uint32_t boxHeight{0};

    // Throws std::invalid_argument when the payload cannot be rendered.
    void validate() const;
    [[nodiscard]] bool isValid() const noexcept;

    [[nodiscard]] bool operator==(const TextLayerData&) const = default;
};

// True when the style values are within the supported ranges.
[[nodiscard]] bool isValidTextStyle(const TextStyle& style) noexcept;

// True when the box dimensions are usable: fixed boxes must be non-zero and
// within the shared limits; auto-sized boxes ignore the stored dimensions but
// still reject out-of-range values.
[[nodiscard]] bool isValidTextBox(
    bool autoSize,
    std::uint32_t boxWidth,
    std::uint32_t boxHeight
) noexcept;

// Alignment <-> string conversions kept Qt-free so the engine can round-trip
// text metadata without the application layer.
[[nodiscard]] const char* textHorizontalAlignName(
    TextHorizontalAlign align
) noexcept;
[[nodiscard]] const char* textVerticalAlignName(TextVerticalAlign align) noexcept;
[[nodiscard]] bool parseTextHorizontalAlign(
    const std::string& value,
    TextHorizontalAlign& out
) noexcept;
[[nodiscard]] bool parseTextVerticalAlign(
    const std::string& value,
    TextVerticalAlign& out
) noexcept;

} // namespace glyma::core
